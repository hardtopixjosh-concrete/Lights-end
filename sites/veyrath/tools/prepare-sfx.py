"""Oct 19: copy the chosen recorded SFX into dist/assets/audio/sfx and write its manifest.json.

Map file (default tools/sfx-map.json):
  {"packs": {"kenney-impact": "C:/.../VEYRATH/Sounds/packs/kenney_impact-sounds"},
   "sounds": {"boss-smash": {"files": ["kenney-impact:Audio/impactPunch_heavy_000.ogg", ...], "gain": .7, "pitch": .06}}}
Keys in "sounds" are sound.js kinds (e.g. 'boss-roar', 'pyro-meteor', 'w-bow', 'pickup-gold'); any kind listed
here plays the recorded files instead of its synth recipe. Source packs stay untouched (only selected files are copied).
.ogg/.mp3 are copied as is; .wav is converted to .ogg with ffmpeg when it is on PATH, otherwise copied as .wav.
"""
import json, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'dist' / 'assets' / 'audio' / 'sfx'

def main(map_path):
    spec = json.loads(Path(map_path).read_text(encoding='utf-8'))
    base = Path(map_path).resolve().parent  # pack paths are relative to the map file
    packs = {k: (base / v).resolve() for k, v in spec.get('packs', {}).items()}
    OUT.mkdir(parents=True, exist_ok=True)
    ffmpeg = shutil.which('ffmpeg')
    sounds = {}
    for kind, d in spec['sounds'].items():
        files = []
        for i, ref in enumerate(d['files']):
            pack, _, rel = ref.partition(':')
            src = packs[pack] / rel if rel else Path(ref)
            if not src.exists():
                sys.exit(f'missing {src} (for {kind})')
            ext = src.suffix.lower()
            name = f'{kind}-{i + 1}'
            if ext == '.wav' and ffmpeg:
                dst = OUT / (name + '.ogg')
                subprocess.run([ffmpeg, '-y', '-loglevel', 'error', '-i', str(src), '-c:a', 'libvorbis', '-q:a', '5', str(dst)], check=True)
            else:
                dst = OUT / (name + ext)
                shutil.copyfile(src, dst)
            files.append(dst.name)
        sounds[kind] = {'files': files, 'gain': d.get('gain', .6), 'pitch': d.get('pitch', .06)}
    manifest = {'_note': 'Generated by tools/prepare-sfx.py from ' + Path(map_path).name, 'sounds': sounds}
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=1), encoding='utf-8')
    print(f'{len(sounds)} sounds, {sum(len(s["files"]) for s in sounds.values())} files -> {OUT}')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else ROOT / 'tools' / 'sfx-map.json')
